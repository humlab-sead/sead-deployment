"""Builds human-brief/data.js, the data behind the interactive brief (human-brief/index.html).

Inputs, all in this supporting/ directory unless given:
  brief.json                 output of export_human_brief_data.sql
  context.json               output of export_human_brief_context.sql (country outlines)
  region_polygon_matches.csv country of every Region-filter location
  non_regions.json           the 226 locations that are not regions, with their kind

Usage: python3 -I build_human_brief_data.py BRIEF_JSON CONTEXT_JSON OUT_JS
"""
import csv
import json
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
brief_path, context_path, out_path = sys.argv[1:4]

brief = json.load(open(brief_path, encoding="utf-8"))
context = json.load(open(context_path, encoding="utf-8"))
matches = {int(r["location_id"]): r for r in csv.DictReader(open(os.path.join(here, "region_polygon_matches.csv"), encoding="utf-8"))}
non_regions = {r["id"]: r["kind"] for r in json.load(open(os.path.join(here, "non_regions.json"), encoding="utf-8"))}

links_by_loc = {}
for link in brief["links"]:
    links_by_loc.setdefault(link["loc"], []).append(link)

locations = []
for loc in brief["locations"]:
    lid = loc["id"]
    m = matches[lid]
    country = m["country"]
    links = links_by_loc.get(lid, [])
    if links:
        group, sub = "linked", links[0]["mt"]
    elif lid in non_regions:
        group, sub = "nonregion", non_regions[lid]
    elif country == "Denmark":
        group, sub = "missing", "danish"
    elif country != "Sweden":
        group, sub = "missing", "foreign"
    elif m["cls"] == "socken":
        group, sub = "missing", "swedish_parish"
    else:
        group, sub = "missing", "other"
    locations.append({
        "id": lid, "name": loc["name"], "country": country, "group": group, "sub": sub,
        "sites": loc["sites"],
        "links": [{"src": l["src"], "key": l["key"], "note": l["note"], "inside": l["inside"]} for l in links],
    })

data = {
    "locations": locations,
    "sites": brief["sites"],
    "boundaries": brief["boundaries"],
    "context": context,
}
with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Generated by supporting/build_human_brief_data.py. Do not edit by hand.\n")
    f.write("window.BRIEF_DATA = ")
    json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

counts = {}
for l in locations:
    counts[(l["group"], l["sub"])] = counts.get((l["group"], l["sub"]), 0) + 1
for k in sorted(counts):
    print(k, counts[k])
print("total", len(locations))
