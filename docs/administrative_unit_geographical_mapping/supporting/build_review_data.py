"""Writes review/data.js, the data behind the site review page (review/index.html).

Usage: python3 -I build_review_data.py REVIEW_JSON SITE_REGIONS_JSON OUT_JS
  REVIEW_JSON        output of export_site_review.sql
  SITE_REGIONS_JSON  {site_id: {name, regions: [[location_id, location_name, location_type_id, location_type], ...]}}
                     from SEAD: every region each site is linked to, whether or not it has a boundary
"""
import json
import sys

review_path, regions_path, out_path = sys.argv[1:4]
review = json.load(open(review_path, encoding="utf-8"))
site_regions = json.load(open(regions_path, encoding="utf-8"))

review["sites"] = review.get("sites") or []
for site in review["sites"]:
    info = site_regions.get(str(site["site_id"]), {})
    site["name"] = info.get("name", "")
    site["regions"] = info.get("regions", [])
    site["checks"] = site.get("checks") or []

with open(out_path, "w", encoding="utf-8") as f:
    f.write("// Generated by supporting/run_build_mapping.sh. Do not edit by hand.\n")
    f.write("window.REVIEW_DATA = ")
    json.dump(review, f, ensure_ascii=False, separators=(",", ":"))
    f.write(";\n")

n_q = sum(1 for s in review["sites"] for c in s["checks"] if not c["inside"])
n_near = sum(1 for s in review["sites"] for c in s["checks"] if not c["inside"] and c["near_pair"])
print(f"Wrote {out_path}: {len(review['sites'])} sites, {n_q} questions ({n_near} within 2 km, signing off a boundary link)")
